#!/usr/bin/env python3
"""Generate Copilot, Claude Code and OpenCode files from the neutral Thunai source.

Sources: .thunai/src/ (agents, rules, commands), skills/ (canonical skills, read-only here), AGENTS.md.
Skills are NOT copied: each runtime gets a tiny entry point that points at skills/<name>/SKILL.md.
OpenCode also reads .claude/skills and the "skills": ["./skills"] entry in opencode.jsonc.

Usage:
  python .thunai/sync.py           write generated files
  python .thunai/sync.py --check   exit 1 if any generated file is missing or out of date
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".thunai" / "src"
GEN = "<!-- GENERATED by .thunai/sync.py from .thunai/src, skills/ and AGENTS.md. Do not edit; change the source and re-run. -->"

# ---- role -> tool / permission mappings -------------------------------------------------
# Entry-point descriptions for the two imported upstream skills (kept from the original project stubs).
STUB_DESCRIPTIONS = {
    "test-driven-development": "Follow test-first red-green-refactor for implementation and behavior changes. Load before writing implementation code.",
    "systematic-debugging": "Investigate root causes before suggesting fixes for bugs, test failures, or unexpected behavior.",
}
SKILL_ENTRY_DIRS = (".claude/skills", ".github/skills")
LEGACY = {
    ".opencode/opencode.jsonc": "old OpenCode config; replaced by the root opencode.jsonc (delete it, or OpenCode merges two configs)",
    ".opencode/skills": "full skill copies from an earlier kit; skills now live only in skills/ (delete this folder)",
}
MANAGED_DIRS = (".github/agents", ".github/instructions", ".github/prompts", ".github/skills",
                ".claude/agents", ".claude/commands", ".claude/skills",
                ".opencode/agents", ".opencode/commands")

COPILOT_TOOLS = {
    "orchestrator": ["read", "search", "edit", "execute", "agent", "todo"],
    "write": ["read", "search", "edit", "execute"],
    "review": ["read", "search", "execute"],
    "plan": ["read", "search"],
}
CLAUDE_TOOLS = {
    "orchestrator": ["Read", "Write", "Edit", "Glob", "Grep", "Bash", "Skill"],
    "write": ["Read", "Write", "Edit", "Glob", "Grep", "Bash", "Skill"],
    "review": ["Read", "Glob", "Grep", "Bash", "Skill"],
    "plan": ["Read", "Glob", "Grep", "Skill"],
}
OC_EDIT = {"orchestrator": "ask", "write": "allow", "review": "deny", "plan": "deny"}
OC_BASH = [
    ("*", "ask"),
    # every git/gh write asks
    ("git add*", "ask"), ("git commit*", "ask"), ("git push*", "ask"), ("git merge*", "ask"),
    ("git rebase*", "ask"), ("git reset*", "ask"), ("git checkout*", "ask"), ("git switch*", "ask"),
    ("git restore*", "ask"), ("git stash*", "ask"), ("git tag*", "ask"), ("git cherry-pick*", "ask"),
    ("git revert*", "ask"), ("git clean*", "ask"), ("git pull*", "ask"), ("git rm*", "ask"),
    ("gh pr *", "ask"), ("gh issue *", "ask"), ("gh release *", "ask"), ("gh repo *", "ask"),
    ("gh workflow *", "ask"), ("gh api *", "ask"),
    # read-only
    ("git status*", "allow"), ("git diff*", "allow"), ("git log*", "allow"), ("git show*", "allow"),
    ("git fetch*", "allow"), ("git branch --show-current", "allow"), ("git stash list*", "allow"),
    ("gh auth status*", "allow"), ("gh issue list*", "allow"), ("gh issue view*", "allow"),
    ("gh pr list*", "allow"), ("gh pr view*", "allow"), ("gh pr diff*", "allow"), ("gh pr checks*", "allow"),
    ("python .thunai/scripts/orient_snapshot.py*", "allow"),
    # hard denies (last match wins)
    ("git add .", "deny"), ("git add -A*", "deny"), ("git add --all*", "deny"),
    ("git push --force*", "deny"), ("git push -f*", "deny"),
]


def parse(text):
    text = text.replace("\r\n", "\n")
    m = re.match(r"---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        raise ValueError("missing frontmatter")
    meta = {}
    for line in m.group(1).split("\n"):
        if line.strip():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, m.group(2).lstrip("\n")


def copilot_name(name):
    return "*" + "_".join(p.capitalize() for p in name.split("-"))


def sub_agents(body, target):
    def repl(m):
        n = m.group(1)
        return copilot_name(n) if target == "copilot" else n
    return re.sub(r"\{\{agent:([a-z-]+)\}\}", repl, body)


def fm(pairs):
    return "---\n" + "\n".join(f"{k}: {v}" for k, v in pairs) + "\n---\n"


def q(s):
    """YAML double-quoted scalar."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build():
    out = {}

    def emit(rel, text):
        out[rel] = text.replace("\r\n", "\n").encode("utf-8")

    # ---- agents ------------------------------------------------------------------------
    for f in sorted((SRC / "agents").glob("*.md")):
        meta, body = parse(f.read_text(encoding="utf-8"))
        name, role, desc = meta["name"], meta["role"], meta["description"]
        delegates = [d.strip() for d in meta.get("delegates", "").split(",") if d.strip()]

        # Copilot
        pairs = [("name", f"'{copilot_name(name)}'"), ("description", q(desc)),
                 ("tools", "[" + ", ".join(COPILOT_TOOLS[role]) + "]")]
        if delegates:
            pairs.append(("agents", "[" + ", ".join(f"'{copilot_name(d)}'" for d in delegates) + "]"))
        pairs.append(("user-invocable", "true"))
        emit(f".github/agents/{name}.agent.md",
             fm(pairs) + GEN + "\n\n" + sub_agents(body, "copilot"))

        # Claude Code
        tools = list(CLAUDE_TOOLS[role])
        if delegates:
            tools.append("Task(" + ", ".join(delegates) + ")")
        emit(f".claude/agents/{name}.md",
             fm([("name", name), ("description", q(desc)), ("tools", ", ".join(tools))])
             + GEN + "\n\n" + sub_agents(body, "claude"))

        # OpenCode
        lines = ["permission:", f"  edit: {OC_EDIT[role]}"]
        if role == "plan":
            lines.append("  bash: deny")
        else:
            lines.append("  bash:")
            lines += [f'    "{p}": {a}' for p, a in OC_BASH]
        lines += ["  skill:", '    "*": allow']
        if delegates:
            lines += ["  task:", '    "*": deny'] + [f'    "{d}": allow' for d in delegates]
        else:
            lines.append("  task: deny")
        mode = "primary" if role == "orchestrator" else "subagent"
        emit(f".opencode/agents/{name}.md",
             "---\n" + f"description: {q(desc)}\nmode: {mode}\n" + "\n".join(lines) + "\n---\n"
             + GEN + "\n\n" + sub_agents(body, "opencode"))

    # ---- rules (Copilot instruction files) ----------------------------------------------
    for f in sorted((SRC / "rules").glob("*.md")):
        meta, body = parse(f.read_text(encoding="utf-8"))
        emit(f".github/instructions/{f.stem}.instructions.md",
             fm([("description", q(meta["description"])), ("applyTo", q(meta.get("applyTo", "**")))])
             + GEN + "\n\n" + body)

    # ---- commands / prompts --------------------------------------------------------------
    for f in sorted((SRC / "commands").glob("*.md")):
        meta, body = parse(f.read_text(encoding="utf-8"))
        agent, desc = meta["agent"], meta["description"]
        emit(f".github/prompts/{f.stem}.prompt.md",
             fm([("agent", q(copilot_name(agent))), ("description", q(desc))]) + GEN + "\n\n"
             + sub_agents(body, "copilot").replace("{{args}}", "${input:task:Issue number or task description}"))
        emit(f".claude/commands/{f.stem}.md",
             fm([("description", q(desc)), ("argument-hint", "[issue-or-task]")]) + GEN + "\n\n"
             + (f"Delegate this to the `{agent}` subagent.\n\n" if agent != "thunai" else "")
             + sub_agents(body, "claude").replace("{{args}}", "$ARGUMENTS"))
        emit(f".opencode/commands/{f.stem}.md",
             fm([("description", q(desc)), ("agent", agent)]) + GEN + "\n\n"
             + sub_agents(body, "opencode").replace("{{args}}", "$ARGUMENTS"))

    # ---- skills: tiny entry points that refer to the canonical skills/<name>/SKILL.md --------
    for skill_md in sorted((ROOT / "skills").glob("*/SKILL.md")):
        meta, _ = parse(skill_md.read_text(encoding="utf-8"))
        name = skill_md.parent.name
        if meta.get("name") != name:
            raise ValueError(f"skills/{name}/SKILL.md: frontmatter name '{meta.get('name')}' must equal the folder name")
        desc = STUB_DESCRIPTIONS.get(name, meta["description"])
        body = (f"Use the canonical shared instructions here: @skills/{name}/SKILL.md\n\n"
                f"If that file is not already in context, read `skills/{name}/SKILL.md` first. "
                f"Files it links to (templates, scripts, references) live in `skills/{name}/`.\n")
        for base in SKILL_ENTRY_DIRS:
            emit(f"{base}/{name}/SKILL.md", fm([("name", name), ("description", q(desc))]) + GEN + "\n\n" + body)

    # ---- always-on instructions (Copilot copy of AGENTS.md) ------------------------------
    agents_md = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    emit(".github/copilot-instructions.md", GEN + "\n\n" + agents_md)
    return out


def stale_files(out):
    """Generated files (carrying the GEN marker) that the current source no longer produces."""
    stale = []
    for d in MANAGED_DIRS:
        base = ROOT / d
        if not base.exists():
            continue
        for f in sorted(p for p in base.rglob("*") if p.is_file()):
            rel = f.relative_to(ROOT).as_posix()
            if rel in out:
                continue
            try:
                if "GENERATED by .thunai/sync.py" in f.read_text(encoding="utf-8", errors="ignore"):
                    stale.append(f)
            except OSError:
                pass
    return stale


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = build()
    drift = 0
    for rel, data in sorted(out.items()):
        path = ROOT / rel
        current = path.read_bytes().replace(b"\r\n", b"\n") if path.exists() else None
        if current == data:
            continue
        drift += 1
        if args.check:
            print(f"DRIFT  {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"wrote  {rel}")
    for rel, why in LEGACY.items():
        if (ROOT / rel).exists():
            print(f"WARN   {rel}: {why}")
    for f in stale_files(out):
        drift += 1
        rel = f.relative_to(ROOT).as_posix()
        if args.check:
            print(f"STALE  {rel}")
        else:
            f.unlink()
            try:
                f.parent.rmdir()
            except OSError:
                pass
            print(f"removed {rel}")
    if args.check:
        print("in sync" if not drift else f"{drift} file(s) out of date; run: python .thunai/sync.py")
        sys.exit(1 if drift else 0)
    print(f"done: {len(out)} generated files, {drift} changed")


if __name__ == "__main__":
    main()
