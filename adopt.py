#!/usr/bin/env python3
"""Install Thunai into an EXISTING repository in one command.

Usage (run from a clone or download of the template):
  python adopt.py ../my-repo
  python adopt.py ../my-repo --dry-run
  python adopt.py ../my-repo --non-interactive --name "Acme Shop" --packs web-nextjs

What it does:
  1. copies .thunai/, skills/, AGENTS.md, CLAUDE.md (plus init.py and packs/ temporarily)
     and skips the template's own docs, licence, CI and community files
  2. MERGES, never overwrites: .gitignore, .gitattributes, .vscode/settings.json, .claude/settings.json
  3. runs init.py inside the target (name, branch prefix, teams, packs, sync)
  4. removes init.py and packs/ from the target (use --keep-init to keep them)

It refuses to run when AGENTS.md, CLAUDE.md or .github/copilot-instructions.md already exist
and are not Thunai-generated, unless you pass --force; those files are then saved as
<name>.pre-thunai first. It never runs git. Review the result with `git status` and commit it yourself.
"""
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent
GENERATED_MARKER = "GENERATED by .thunai/sync.py"
SKIP = {
    Path(".thunai/docs"),
    Path(".thunai/scripts/validate_template.py"),
    Path(".thunai/scripts/smoke_init.py"),
}
ROOT_FILES = ["AGENTS.md", "CLAUDE.md"]
GITIGNORE_LINES = [".thunai/tracking/*", "!.thunai/tracking/EXAMPLE.md", ".thunai/memory/session/"]
GITATTRIBUTES_LINES = [
    "skills/** text eol=lf",
    ".thunai/** text eol=lf",
    ".github/** text eol=lf",
    ".claude/** text eol=lf",
    ".opencode/** text eol=lf",
    "*.py text eol=lf",
]
JSON_MERGES = [Path(".vscode/settings.json"), Path(".claude/settings.json")]
PASSTHROUGH = ("name", "prefix", "packs", "teams", "active_team")


def copy_tree(top, target, dry, log):
    for item in sorted((KIT / top).rglob("*")):
        rel = item.relative_to(KIT)
        if item.is_dir() or "__pycache__" in item.parts or item.suffix == ".pyc":
            continue
        if any(rel == s or s in rel.parents for s in SKIP):
            continue
        dst = target / rel
        if dst.exists():
            log.append(f"  = kept existing {rel}")
            continue
        log.append(f"  + {rel}")
        if not dry:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, dst)


def merge_lines(path, lines, header, dry, log):
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    existing = text.splitlines()
    missing = [ln for ln in lines if ln not in existing]
    if not missing:
        log.append(f"  = {path.name} already has the Thunai lines")
        return
    log.append(f"  ~ {path.name}: adding {len(missing)} line(s)")
    if not dry:
        if text and not text.endswith("\n"):
            text += "\n"
        block = ("\n" if text else "") + header + "\n" + "\n".join(missing) + "\n"
        path.write_text(text + block, encoding="utf-8", newline="")


def deep_merge(base, extra, path, kept):
    """Add what `extra` has and `base` lacks; on a scalar clash keep `base` and record it."""
    for key, val in extra.items():
        here = f"{path}.{key}" if path else key
        if key not in base:
            base[key] = val
        elif isinstance(base[key], dict) and isinstance(val, dict):
            deep_merge(base[key], val, here, kept)
        elif isinstance(base[key], list) and isinstance(val, list):
            base[key].extend(v for v in val if v not in base[key])
        elif base[key] != val:
            kept.append(here)
    return base


def merge_json(rel, target, dry, log):
    src = KIT / rel
    dst = target / rel
    if not src.is_file():
        return
    if not dst.exists():
        log.append(f"  + {rel}")
        if not dry:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        return
    try:
        base = json.loads(dst.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        log.append(f"  ! {rel} is not strict JSON (comments?); left untouched. Merge {src} into it by hand.")
        return
    kept = []
    merged = deep_merge(base, json.loads(src.read_text(encoding="utf-8")), "", kept)
    note = f"; kept your values for {', '.join(kept)}" if kept else ""
    log.append(f"  ~ {rel}: merged Thunai settings{note}")
    if not dry:
        dst.write_text(json.dumps(merged, indent=2) + "\n", encoding="utf-8", newline="")


def conflicts(target):
    found = []
    for rel in ("AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md"):
        f = target / rel
        if f.is_file() and GENERATED_MARKER not in f.read_text(encoding="utf-8", errors="ignore"):
            found.append(rel)
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", help="path to the existing repository")
    ap.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    ap.add_argument("--force", action="store_true", help="replace existing AGENTS.md/CLAUDE.md/copilot-instructions.md (backed up as .pre-thunai)")
    ap.add_argument("--keep-init", action="store_true", help="keep init.py and packs/ in the target")
    ap.add_argument("--no-init", action="store_true", help="copy and merge only; run init.py yourself later")
    ap.add_argument("--non-interactive", action="store_true")
    ap.add_argument("--name")
    ap.add_argument("--prefix")
    ap.add_argument("--packs")
    ap.add_argument("--teams")
    ap.add_argument("--active-team")
    args = ap.parse_args()

    target = Path(args.target).resolve()
    if not target.is_dir():
        print(f"error: not a directory: {target}", file=sys.stderr)
        return 2
    if target == KIT:
        print("error: target is the template itself; use init.py there", file=sys.stderr)
        return 2
    if (target / ".thunai").exists():
        print("error: .thunai already exists in the target; Thunai looks installed already.", file=sys.stderr)
        return 2
    if not (target / ".git").exists():
        print("warning: target has no .git folder. Continuing.")
    clashes = conflicts(target)
    if clashes and not args.force:
        print(f"error: these files exist and are not Thunai-generated: {', '.join(clashes)}", file=sys.stderr)
        print("Re-run with --force to back them up as <name>.pre-thunai and merge them by hand afterwards.", file=sys.stderr)
        return 2

    dry = args.dry_run
    log = []
    for rel in clashes:
        f = target / rel
        backup = f.with_name(f.name + ".pre-thunai")
        log.append(f"  ! {rel} saved as {backup.name}")
        if not dry:
            shutil.copy2(f, backup)
            f.unlink()

    for top in (".thunai", "skills", "packs"):
        copy_tree(top, target, dry, log)
    for name in ROOT_FILES + ["init.py"]:
        dst = target / name
        if dst.exists():
            log.append(f"  = kept existing {name}")
            continue
        log.append(f"  + {name}")
        if not dry:
            shutil.copy2(KIT / name, dst)
    merge_lines(target / ".gitignore", GITIGNORE_LINES, "# Thunai local-only files", dry, log)
    merge_lines(target / ".gitattributes", GITATTRIBUTES_LINES, "# Thunai: LF so sync --check is stable", dry, log)
    for rel in JSON_MERGES:
        merge_json(rel, target, dry, log)

    print(("Dry run: " if dry else "") + f"installing Thunai into {target}")
    print("\n".join(log))
    if dry:
        print("\nNothing written. Re-run without --dry-run to apply.")
        return 0

    if not args.no_init:
        cmd = [sys.executable, "init.py"]
        for key in PASSTHROUGH:
            val = getattr(args, key)
            if val is not None:
                cmd += [f"--{key.replace('_', '-')}", val]
        if args.non_interactive:
            cmd.append("--non-interactive")
        res = subprocess.run(cmd, cwd=target)
        if res.returncode != 0:
            print("init.py failed; fix the error above and re-run `python init.py` in the target.", file=sys.stderr)
            return res.returncode
        if not args.keep_init:
            (target / "init.py").unlink(missing_ok=True)
            shutil.rmtree(target / "packs", ignore_errors=True)
            print("Removed init.py and packs/ from the target (use --keep-init to keep them).")

    print("\nDone. Nothing was committed. Next: `git status`, review, create a branch, and commit it yourself.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
